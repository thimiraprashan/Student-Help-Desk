import mongoose from "mongoose";

const CompanyAuthSchema = new mongoose.Schema(
  {
    companyId: {
      type: Number,
      required: true,
      unique: true,
    },
    name: {
      type: String,
      required: true,
    },
    email: {
      type: String,
      required: true,
      unique: true,
    },
    password: {
      type: String,
      required: true,
    },
  },
  { timestamps: true }
);

export default mongoose.model("CCompanyAuth", CompanyAuthSchema);
